import { writeFile } from "node:fs/promises";
import path from "node:path";
import { type Express } from "express";
import request from "supertest";
import { beforeAll, describe, expect, it } from "vitest";
import { createApp } from "../../src/app.js";
import { deleteImage, ensureUploadDir, saveImage, UPLOAD_ROOT } from "../../src/lib/storage.js";
import { pngBuffer } from "../helpers/images.js";

/** GET /uploads/:filename: only stored images, nothing else on disk. */
let app: Express;
let stored: { filename: string; url: string };

beforeAll(async () => {
  app = createApp();
  stored = await saveImage(pngBuffer(), "image/png");
  // A file that exists in the directory but could never have been generated by the adapter.
  await ensureUploadDir();
  await writeFile(path.join(UPLOAD_ROOT, "notes.txt"), "secret", "utf8");
  await writeFile(path.join(UPLOAD_ROOT, ".hidden.png"), pngBuffer(), "binary");
});

describe("GET /uploads/:filename", () => {
  it("serves a stored image with caching and a cross-origin resource policy", async () => {
    const res = await request(app).get(stored.url);
    expect(res.status).toBe(200);
    expect(res.headers["content-type"]).toMatch(/^image\/png/);
    expect(res.headers["cross-origin-resource-policy"]).toBe("cross-origin");
    expect(res.headers["cache-control"]).toMatch(/max-age=86400/);
    expect(res.headers["x-content-type-options"]).toBe("nosniff");
    expect(res.body.length ?? res.body.byteLength).toBe(pngBuffer().length);
  });

  it("answers 404 in the error envelope for a missing image", async () => {
    const res = await request(app).get("/uploads/0123456789abcdef0123456789abcdef.png");
    expect(res.status).toBe(404);
    expect(res.body.error.code).toBe("NOT_FOUND");
  });

  it.each([
    "/uploads/",
    "/uploads/notes.txt",
    "/uploads/.hidden.png",
    "/uploads/..%2Fpackage.json",
    "/uploads/%2e%2e/package.json",
    "/uploads/0123456789abcdef0123456789abcdef.png%00.txt",
    "/uploads/0123456789abcdef.svg",
  ])("refuses anything that is not a stored image name: %s", async (url) => {
    const res = await request(app).get(url);
    expect(res.status).toBe(404);
    expect(res.body.error.code).toBe("NOT_FOUND");
  });

  it("does not serve the image after it was deleted", async () => {
    const other = await saveImage(pngBuffer(), "image/png");
    expect((await request(app).get(other.url)).status).toBe(200);
    expect(await deleteImage(other.filename)).toBe(true);
    expect((await request(app).get(other.url)).status).toBe(404);
  });
});
